#!/usr/bin/env python3
"""Backfill extensive per-task PTB-XL metrics from saved probabilities.

This is intentionally inference-free: it recomputes deterministic metrics from
the provenance-preserving per-record Parquet outputs generated by the frozen
ECGFounder and five-superclass classifiers.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from scripts.clinical_metrics import multilabel_classification_metrics
from scripts.evaluate_comprehensive_registry import CLASS_NAMES, json_safe


PROJECT_ROOT = Path(__file__).resolve().parents[1]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _stack(frame: pd.DataFrame, column: str) -> np.ndarray:
    if column not in frame:
        raise ValueError(f"Required column {column!r} is absent")
    values = np.stack(frame[column].to_numpy())
    if not np.isfinite(values).all():
        raise ValueError(f"Non-finite values in {column!r}")
    return values


def _rows(
    *,
    model: dict[str, Any],
    classifier: str,
    signal_variant: str,
    metrics: dict[str, Any],
    source_path: Path,
) -> list[dict[str, Any]]:
    output = []
    for task_name, task in metrics["per_task"].items():
        output.append(
            {
                "dataset": "PTB-XL_fold10",
                "evaluation_type": "real_gt",
                "classifier": classifier,
                "signal_variant": signal_variant,
                "model_id": model["id"],
                "family": model["family"],
                "factorial_mask": model.get("factorial_mask")
                or model.get("loss", {}).get("factorial_mask"),
                "task_name": task_name,
                "source_parquet": str(source_path.relative_to(PROJECT_ROOT)),
                **task,
            }
        )
    return output


def backfill(
    comprehensive_path: Path,
    registry_path: Path,
    output_path: Path,
    database_path: Path,
) -> dict[str, Any]:
    comprehensive = json.loads(comprehensive_path.read_text())
    registry = json.loads(registry_path.read_text())
    task_path = PROJECT_ROOT / registry["ecgfounder_tasks"]
    ecgfounder_tasks = [
        line.strip() for line in task_path.read_text().splitlines() if line.strip()
    ]
    registry_by_id = {model["id"]: model for model in registry["models"]}
    payload: dict[str, Any] = {
        "schema_version": 3,
        "protocol": {
            "dataset": "PTB-XL",
            "split": "fold10_test",
            "n_records": 2198,
            "threshold": 0.5,
            "threshold_source": "fixed_predefined_0.5",
            "classifiers": {
                "ecgfounder": {
                    "n_tasks": len(ecgfounder_tasks),
                    "tasks_path": str(task_path.relative_to(PROJECT_ROOT)),
                    "tasks_sha256": sha256_file(task_path),
                },
                "five_superclass": {
                    "n_tasks": len(CLASS_NAMES),
                    "task_names": CLASS_NAMES,
                },
            },
        },
        "models": {},
    }
    database_rows: list[dict[str, Any]] = []
    for model_id, original in comprehensive["models"].items():
        if model_id not in registry_by_id:
            raise ValueError(f"Result model is absent from registry: {model_id}")
        model = {
            "id": model_id,
            "family": registry_by_id[model_id]["family"],
            "factorial_mask": registry_by_id[model_id].get("factorial_mask"),
        }
        model_payload: dict[str, Any] = {
            **model,
            "classifiers": {},
        }

        ecgfounder_path = PROJECT_ROOT / original["ecgfounder_per_record_parquet"]
        founder = pd.read_parquet(ecgfounder_path)
        labels = _stack(founder, "labels")
        reconstructed = _stack(founder, "probabilities")
        reference = _stack(founder, "reference_probabilities")
        if labels.shape != (2198, len(ecgfounder_tasks)):
            raise ValueError(f"Unexpected ECGFounder shape for {model_id}: {labels.shape}")
        founder_reconstructed = multilabel_classification_metrics(
            reconstructed,
            labels,
            ecgfounder_tasks,
            threshold_source="fixed_predefined_0.5",
        )
        founder_reference = multilabel_classification_metrics(
            reference,
            labels,
            ecgfounder_tasks,
            threshold_source="fixed_predefined_0.5",
        )
        model_payload["classifiers"]["ecgfounder"] = {
            "per_record_parquet": str(ecgfounder_path.relative_to(PROJECT_ROOT)),
            "per_record_sha256": sha256_file(ecgfounder_path),
            "reconstructed": founder_reconstructed,
            "reference": founder_reference,
        }
        database_rows.extend(
            _rows(
                model=model,
                classifier="ECGFounder_150",
                signal_variant="reconstructed",
                metrics=founder_reconstructed,
                source_path=ecgfounder_path,
            )
        )
        database_rows.extend(
            _rows(
                model=model,
                classifier="ECGFounder_150",
                signal_variant="reference",
                metrics=founder_reference,
                source_path=ecgfounder_path,
            )
        )

        parity_path = PROJECT_ROOT / original["paper_parity_per_record_parquet"]
        parity = pd.read_parquet(parity_path)
        parity_labels = _stack(parity, "labels")
        parity_probabilities = _stack(parity, "probabilities")
        if parity_labels.shape != (2198, len(CLASS_NAMES)):
            raise ValueError(
                f"Unexpected five-superclass shape for {model_id}: {parity_labels.shape}"
            )
        parity_metrics = multilabel_classification_metrics(
            parity_probabilities,
            parity_labels,
            CLASS_NAMES,
            threshold_source="fixed_predefined_0.5",
        )
        model_payload["classifiers"]["ptbxl_five_superclass"] = {
            "per_record_parquet": str(parity_path.relative_to(PROJECT_ROOT)),
            "per_record_sha256": sha256_file(parity_path),
            "reconstructed": parity_metrics,
        }
        database_rows.extend(
            _rows(
                model=model,
                classifier="PTBXL_five_superclass",
                signal_variant="reconstructed",
                metrics=parity_metrics,
                source_path=parity_path,
            )
        )
        payload["models"][model_id] = model_payload

    if len(payload["models"]) != 48:
        raise ValueError(f"Expected 48 models, found {len(payload['models'])}")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(json_safe(payload), indent=2, allow_nan=False))
    database = pd.DataFrame.from_records(database_rows)
    database_path.parent.mkdir(parents=True, exist_ok=True)
    database.to_parquet(database_path, index=False)
    database.to_csv(database_path.with_suffix(".csv"), index=False)
    print(
        json.dumps(
            {
                "models": len(payload["models"]),
                "database_rows": len(database),
                "output": str(output_path),
                "database": str(database_path),
            },
            indent=2,
        )
    )
    return payload


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--comprehensive", type=Path, required=True)
    parser.add_argument("--registry", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--database", type=Path, required=True)
    args = parser.parse_args()
    backfill(args.comprehensive, args.registry, args.output, args.database)


if __name__ == "__main__":
    main()
